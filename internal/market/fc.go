type Client struct {
	fc    config.FC
	yahoo config.Yahoo
	http  *http.Client
}

func New(fc config.FC, yahoo config.Yahoo) *Client {
	transport := http.DefaultTransport.(*http.Transport).Clone()
	transport.Proxy = nil
	transport.DisableKeepAlives = true
	return &Client{
		fc: fc, yahoo: yahoo,
		http: &http.Client{
			Transport: transport,
			Timeout:   120 * time.Second,
			CheckRedirect: func(*http.Request, []*http.Request) error {
				return http.ErrUseLastResponse
			},
		},
	}
}

type htmlRequest struct {
	TargetURL   string     `json:"target_url"`
	Assertion   string     `json:"page_loaded_assertion,omitempty"`
	Cookies     *[]cookie  `json:"cookies,omitempty"`
	WaitSeconds int        `json:"max_assertion_wait_seconds,omitempty"`
	Retries     int        `json:"max_retries,omitempty"`
	Evaluate    string     `json:"evaluate_script,omitempty"`
	Search      *pageRules `json:"search,omitempty"`
}

type htmlResponse struct {
	Success     *bool           `json:"success"`
	URL         string          `json:"url"`
	Content     string          `json:"content"`
	Code        string          `json:"code"`
	Error       string          `json:"error"`
	Cloudflare  *bool           `json:"cloudflare_detected"`
	ResultState json.RawMessage `json:"resultState"`
}

func (c *Client) render(ctx context.Context, request htmlRequest) (htmlResponse, error) {
	var response htmlResponse
	err := c.invoke(ctx, c.fc.URL, request, &response)
	return response, err
}

func (c *Client) invoke(ctx context.Context, endpoint string, input, output any) error {
	target, err := url.Parse(endpoint)
	if err != nil || target.Hostname() == "" || target.User != nil ||
		(target.Scheme != "http" && target.Scheme != "https") ||
		c.fc.AccessKeyID == "" || c.fc.AccessKeySecret == "" {
		return FCConfiguration
	}
	payload, err := json.Marshal(input)
	if err != nil {
		return InvalidRequest
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodPost, target.String(), bytes.NewReader(payload))
	if err != nil {
		return FCConfiguration
	}
	date := time.Now().UTC().Format("2006-01-02T15:04:05.000Z")
	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("X-Acs-Date", date)
	request.Header.Set("Authorization", authorization(target, date, c.fc.AccessKeyID, c.fc.AccessKeySecret))
	response, err := c.http.Do(request)
	if err != nil {
		var netErr net.Error
		if errors.As(err, &netErr) && netErr.Timeout() {
			return FCTimeout
		}
		return FCRequestFailed
	}
	defer response.Body.Close()
	const maxResponse = 32 << 20
	raw, err := io.ReadAll(io.LimitReader(response.Body, maxResponse+1))
	if err != nil {
		return FCRequestFailed
	}
	if len(raw) > maxResponse {
		return InvalidResponse
	}
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		var reply struct{ Code string }
		_ = json.Unmarshal(raw, &reply)
		if result := knownFailure(reply.Code); result != "" {
			return result
		}
		switch response.StatusCode {
		case 401, 403:
			return FCAccessDenied
		case 429:
			return RateLimited
		case 504:
			return FCTimeout
		default:
			return FCRequestFailed
		}
	}
	if json.Unmarshal(raw, output) != nil {
		return InvalidResponse
	}
	return nil
}

// Match the current FC trigger signature generated by @alicloud/openapi-util.
func authorization(endpoint *url.URL, date, key, secret string) string {
	const algorithm = "ACS3-HMAC-SHA256"
	const signedHeaders = "content-type;x-acs-date"
	path := endpoint.EscapedPath()
	if path == "" {
		path = "/"
	}
	for _, pair := range [][2]string{{"$", "%24"}, {"+", "%20"}, {"*", "%2A"}, {"%7E", "~"}} {
		path = strings.Replace(path, pair[0], pair[1], 1)
	}
	query := endpoint.Query()
	keys := make([]string, 0, len(query))
	for name := range query {
		keys = append(keys, name)
	}
	slices.Sort(keys)
	parts := make([]string, 0, len(keys))
	for _, name := range keys {
		values := query[name]
		value := strings.ReplaceAll(url.QueryEscape(values[len(values)-1]), "+", "%20")
		parts = append(parts, name+"="+value)
	}
	headers := "content-type:application/json\nx-acs-date:" + date + "\n"
	canonical := strings.Join([]string{http.MethodPost, path, strings.Join(parts, "&"), headers, signedHeaders, ""}, "\n")
	hash := sha256.Sum256([]byte(canonical))
	mac := hmac.New(sha256.New, []byte(secret))
	mac.Write([]byte(algorithm + "\n" + hex.EncodeToString(hash[:])))
	return fmt.Sprintf("%s Credential=%s,SignedHeaders=%s,Signature=%x", algorithm, key, signedHeaders, mac.Sum(nil))
}
